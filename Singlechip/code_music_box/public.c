#include "public.h"

/*******************************************************************************
* 函 数 名      : delay_10us
* 函数功能		   : 延时函数，单位是 10 微秒
* 输    入       : 延时的 10 微秒单位数
* 输    出    	 : 无
*******************************************************************************/

void delay_10us(u16 ten_us)
{
	while(ten_us--);	
}

/*******************************************************************************
* 函 数 名      : delay_ms
* 函数功能		   : 延时函数，单位是 1 毫秒
* 输    入       : 延时的 1 毫秒单位数
* 输    出    	 : 无
*******************************************************************************/

void delay_ms(u16 ms)
{
	u16 i,j;
	for(i=ms;i>0;i--)
		for(j=110;j>0;j--);
}
